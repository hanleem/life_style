"""design/tokens.json 에서 CSS 디자인 토큰을 만든다."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _lin(c: float) -> float:
    return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4


def _lum(hex_: str) -> float:
    h = hex_.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    return 0.2126 * _lin(r) + 0.7152 * _lin(g) + 0.0722 * _lin(b)


def contrast(hex1: str, hex2: str) -> float:
    a, b = _lum(hex1), _lum(hex2)
    hi, lo = max(a, b), min(a, b)
    return (hi + 0.05) / (lo + 0.05)


def _kebab(s: str) -> str:
    return re.sub(r"([A-Z])", lambda m: "-" + m.group(1).lower(), s)


def _colors_css(c: dict) -> str:
    return "".join(f"--{_kebab(k)}:{c[k]};" for k in sorted(c))


def resolved_colors(t: dict, theme: str, mode: str) -> dict:
    """테마의 색 전체(기본 팔레트 위에 테마가 바꾼 색을 얹는다)."""
    return {**t["color"][mode], **((t.get("themes") or {}).get(theme) or {}).get(mode, {})}


def render_css(t: dict) -> str:
    rest = ""
    rest += "".join(f"--radius-{_kebab(k)}:{t['radius'][k]}px;" for k in sorted(t["radius"]))
    rest += "".join(f"--space-{_kebab(k)}:{t['space'][k]}px;" for k in sorted(t["space"]))
    f = t["font"]
    rest += f"--font-family:{f['family']};"
    rest += "".join(f"--font-{_kebab(k)}:{f[k]}px;" for k in sorted(f) if k not in ("family", "large"))
    rest += f"--touch:{t['touch']['web_min_px']}px;"
    out = (
        "/* GENERATED by tools/gen_tokens.py - do not edit. */\n"
        f":root{{{_colors_css(t['color']['light'])}{rest}}}\n"
        "@media (prefers-color-scheme:dark){"
        f":root{{{_colors_css(t['color']['dark'])}}}"
        "}\n"
    )
    # 테마: <html data-theme=...> 로 고른다. 기본 블록 뒤에 와야 덮어쓴다(선택자 우선순위가 같다).
    # :root 가 아닌 속성 선택자라서 인터뷰의 미리보기 카드처럼 안쪽 요소에도 쓸 수 있다.
    for name, th in (t.get("themes") or {}).items():
        if th.get("light"):
            out += f"[data-theme={name}]{{{_colors_css(th['light'])}}}\n"
        if th.get("dark"):
            out += f"@media (prefers-color-scheme:dark){{[data-theme={name}]{{{_colors_css(th['dark'])}}}}}\n"
    if f.get("large"):   # 글씨 크기 "크게"
        out += "[data-font=large]{" + "".join(f"--font-{_kebab(k)}:{v}px;" for k, v in sorted(f["large"].items())) + "}\n"
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--css", required=True)
    a = ap.parse_args()
    tok = json.loads((ROOT / "design/tokens.json").read_text(encoding="utf-8"))
    p = Path(a.css)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(render_css(tok), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
