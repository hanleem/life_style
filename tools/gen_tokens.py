"""design/tokens.json 에서 CSS 디자인 토큰을 만든다."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _lin(c: float) -> float:
    return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4


def _lum(hex_: str) -> float:
    h = hex_.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    return 0.2126 * _lin(r) + 0.7152 * _lin(g) + 0.0722 * _lin(b)


def contrast(hex1: str, hex2: str) -> float:
    a, b = _lum(hex1), _lum(hex2)
    hi, lo = max(a, b), min(a, b)
    return (hi + 0.05) / (lo + 0.05)


def _kebab(s: str) -> str:
    return re.sub(r"([A-Z])", lambda m: "-" + m.group(1).lower(), s)


def _colors_css(c: dict) -> str:
    return "".join(f"--{_kebab(k)}:{c[k]};" for k in sorted(c))


def render_css(t: dict) -> str:
    rest = ""
    rest += "".join(f"--radius-{_kebab(k)}:{t['radius'][k]}px;" for k in sorted(t["radius"]))
    rest += "".join(f"--space-{_kebab(k)}:{t['space'][k]}px;" for k in sorted(t["space"]))
    f = t["font"]
    rest += f"--font-family:{f['family']};"
    rest += "".join(f"--font-{_kebab(k)}:{f[k]}px;" for k in sorted(f) if k != "family")
    rest += f"--touch:{t['touch']['web_min_px']}px;"
    return (
        "/* GENERATED by tools/gen_tokens.py - do not edit. */\n"
        f":root{{{_colors_css(t['color']['light'])}{rest}}}\n"
        "@media (prefers-color-scheme:dark){"
        f":root{{{_colors_css(t['color']['dark'])}}}"
        "}\n"
    )


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--css", required=True)
    a = ap.parse_args()
    tok = json.loads((ROOT / "design/tokens.json").read_text(encoding="utf-8"))
    p = Path(a.css)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(render_css(tok), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
